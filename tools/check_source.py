"""Check a source export for private paths, large artifacts and broken doc links."""
import argparse
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

FORBIDDEN_SUFFIXES={'.pt','.pth','.ckpt','.mp4','.avi','.mov','.npy','.npz','.zip','.exe','.dll','.pyc'}
FORBIDDEN_PARTS={'.git','__pycache__','.venv','validation','outputs','evaluation_data','node_modules'}
PRIVATE_PATH=re.compile(r'(?i)[A-Z]:[/\\](?:Users|Anaconda|Program Files)[/\\]')
SECRET=re.compile(r'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|(?:ghp_|github_pat_)[A-Za-z0-9_]{25,}|AKIA[0-9A-Z]{16}')


def check(root):
    errors=[];count=0
    for p in root.rglob('*'):
        rel=p.relative_to(root)
        # Git metadata and generated bytecode may exist after running tests locally.
        if '.git' in rel.parts or '__pycache__' in rel.parts:continue
        if p.is_symlink() or (hasattr(p,'is_junction') and p.is_junction()):errors.append(f'link: {rel}');continue
        if not p.is_file():continue
        count+=1
        if p.suffix.lower() in FORBIDDEN_SUFFIXES or any(x in FORBIDDEN_PARTS for x in rel.parts):errors.append(f'artifact: {rel}')
        if p.stat().st_size>2_000_000:errors.append(f'oversize: {rel}')
        if p.name in ('python_path.txt','target_videos.json','evaluation_dataset.json'):errors.append(f'private config: {rel}')
        try:text=p.read_text(encoding='utf-8-sig')
        except UnicodeError:errors.append(f'non-text file: {rel}');continue
        if PRIVATE_PATH.search(text) or SECRET.search(text):errors.append(f'private path or credential pattern: {rel}')
        if p.suffix=='.md':
            for target in re.findall(r'\]\(([^)]+)\)',text):
                target=target.split(' "',1)[0].strip('<>');url=urlsplit(target)
                if url.scheme or not url.path:continue
                dest=(p.parent/unquote(url.path)).resolve()
                if not dest.is_relative_to(root.resolve()) or not dest.exists():errors.append(f'broken local link: {rel} -> {target}')
    if errors:raise ValueError('\n'.join(errors))
    print(f'Source check passed: {count} files (pattern scan, not a comprehensive secret audit)')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('root',type=Path,nargs='?',default=Path(__file__).resolve().parents[1]);check(parser.parse_args().root)
